import { useEffect, useState } from "react";
import { createPortal } from "react-dom";
import { generateAiReview, getAiReviews } from "../../api/changeRequests";
import { extractApiError } from "../../utils/apiError";
import { isAssignedReviewer } from "../../utils/requestPermissions";
import { formatDate, formatEnumLabel } from "../../utils/requestPresentation";

const SCOPES = {
  changed_files: {
    label: "Changed files",
    help: "The diff and the full content of the changed files.",
  },
  extended: {
    label: "Extended",
    help: "Also files they import or are imported by, and top-level config files.",
  },
};

const SKIP_REASONS = {
  removed: "removed in this PR",
  binary: "binary file",
  too_large: "over 200 KB",
  size_limit: "input size limit reached",
  unavailable: "not available",
};

function parseList(value) {
  if (Array.isArray(value)) return value;
  try {
    const parsed = JSON.parse(value || "[]");
    return Array.isArray(parsed) ? parsed.filter((item) => typeof item === "string") : [];
  } catch {
    return [];
  }
}

function PlainList({ title, items, empty }) {
  return (
    <div className="ai-review-block">
      <span className="detail-label">{title}</span>
      {items.length === 0 ? (
        <p>{empty}</p>
      ) : (
        <ul className="ai-review-list">
          {items.map((item, index) => (
            <li key={index}>{item}</li>
          ))}
        </ul>
      )}
    </div>
  );
}

// Mirrors the backend limit (github_service.MAX_CHANGED_FILES).
const MAX_CHANGED_FILES = 100;

function coverageWarnings(result) {
  const warnings = [];
  if (result.changed_files_total > MAX_CHANGED_FILES) {
    warnings.push(`only the first ${MAX_CHANGED_FILES} of ${result.changed_files_total} changed files were covered`);
  }
  // A removed file's diff is still reviewed; that is not a gap.
  const skipped = (result.files_skipped ?? []).filter((f) => f.reason !== "removed").length;
  if (skipped) {
    warnings.push(`${skipped} file(s) skipped`);
  }
  if (result.input_truncated) {
    warnings.push("the input was cut at the size limit");
  }
  if (result.secrets_masked) {
    warnings.push(`${result.secrets_masked} secret value(s) masked`);
  }
  return warnings;
}

function AiReviewResult({ result, requestRiskLevel }) {
  const redFlags = parseList(result.red_flags);
  const checklist = parseList(result.verification_checklist);
  const suggestions = parseList(result.improvement_suggestions);
  const riskDiffers =
    result.suggested_risk_level && requestRiskLevel && result.suggested_risk_level !== requestRiskLevel;
  const warnings = coverageWarnings(result);
  const files = result.files_reviewed ?? [];
  const skipped = result.files_skipped ?? [];

  const footer = [
    result.reviewed_commit ? `Based on commit ${result.reviewed_commit.slice(0, 7)}` : "Based on an unknown commit",
    `${files.length} file${files.length === 1 ? "" : "s"}`,
    result.review_scope ? SCOPES[result.review_scope]?.label ?? result.review_scope : null,
    result.model_name,
    formatDate(result.created_at),
  ].filter(Boolean);

  return (
    <div>
      <span className="git-context-badge">Advisory only, does not affect the approval decision</span>

      {warnings.length > 0 && (
        <div className="ai-review-warning" role="note">
          ⚠ {warnings.join(" · ")}
        </div>
      )}

      <div className="ai-review-block">
        <span className="detail-label">Summary</span>
        <p className="ai-review-summary">{result.summary || "—"}</p>
      </div>

      <div className="details-grid" style={{ marginBottom: "16px" }}>
        <div className={`detail-box${riskDiffers ? " ai-review-risk-differs" : ""}`}>
          <span className="detail-label">Suggested risk level</span>
          <strong>{formatEnumLabel(result.suggested_risk_level) || "—"}</strong>
          <span className="form-hint" style={{ marginTop: 4 }}>
            Request: {formatEnumLabel(requestRiskLevel) || "—"}
            {riskDiffers && " (differs)"}
          </span>
        </div>
        <div className="detail-box">
          <span className="detail-label">Recommended reviewer role</span>
          <strong>{formatEnumLabel(result.recommended_reviewer_role) || "—"}</strong>
          {result.impact_area && (
            <span className="form-hint" style={{ marginTop: 4 }}>
              Impact: {result.impact_area}
            </span>
          )}
        </div>
      </div>

      <PlainList title="Red flags" items={redFlags} empty="None found." />
      <PlainList title="Verification checklist" items={checklist} empty="Nothing listed." />
      <PlainList title="Improvement suggestions" items={suggestions} empty="Nothing listed." />

      <details className="ai-review-footer">
        <summary>
          {footer.join(" · ")}
          {result.generated_by_role && ` · generated by ${formatEnumLabel(result.generated_by_role)}`}
        </summary>
        {files.length > 0 && (
          <ul className="ai-review-files">
            {files.map((file) => (
              <li key={file.path}>
                <span className="git-monospace">{file.path}</span>
                {file.source !== "changed" && <span className="form-hint ai-review-file-note">{file.source}</span>}
              </li>
            ))}
          </ul>
        )}
        {skipped.length > 0 && (
          <>
            <span className="detail-label" style={{ marginTop: 10 }}>Skipped</span>
            <ul className="ai-review-files">
              {skipped.map((file) => (
                <li key={file.path}>
                  <span className="git-monospace">{file.path}</span>
                  <span className="form-hint ai-review-file-note">{SKIP_REASONS[file.reason] ?? file.reason}</span>
                </li>
              ))}
            </ul>
          </>
        )}
        {files.length === 0 && skipped.length === 0 && <p className="form-hint">No file list recorded.</p>}
      </details>
    </div>
  );
}

const AI_REVIEW_UNCHANGED = "ai_review_unchanged";

function UnchangedDialog({ message, onCancel, onConfirm }) {
  return createPortal(
    <div className="modal-overlay" onClick={onCancel}>
      <div className="confirm-modal" role="dialog" aria-modal="true" onClick={(e) => e.stopPropagation()}>
        <div className="confirm-modal-header">
          <h3>Nothing has changed</h3>
        </div>
        <div className="confirm-modal-body">
          <p>{message}</p>
          <p className="form-hint">
            The AI would see the same input as for the latest review. Generating again costs another AI call.
          </p>
        </div>
        <div className="confirm-modal-actions">
          <button type="button" className="btn btn-secondary" onClick={onCancel}>
            Cancel
          </button>
          <button type="button" className="btn btn-primary" onClick={onConfirm}>
            Generate anyway
          </button>
        </div>
      </div>
    </div>,
    document.body
  );
}

export default function AiReviewSection({ request, user, onError }) {
  // Every stored result, newest first; `index` is the one shown (0 = latest).
  const [results, setResults] = useState([]);
  const [index, setIndex] = useState(0);
  const [isLoading, setIsLoading] = useState(true);
  const [isGenerating, setIsGenerating] = useState(false);
  const [scope, setScope] = useState("changed_files");
  const [unchanged, setUnchanged] = useState(null); // message of the "nothing changed" warning

  const requestId = request.id;
  const shown = results[index] ?? null;
  const latest = results[0] ?? null;

  useEffect(() => {
    let cancelled = false;
    setIsLoading(true);
    getAiReviews(requestId)
      .then((data) => {
        if (!cancelled) {
          setResults(Array.isArray(data) ? data : []);
          setIndex(0);
        }
      })
      .catch(() => {
        if (!cancelled) setResults([]);
      })
      .finally(() => {
        if (!cancelled) setIsLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [requestId]);

  const canGenerate =
    isAssignedReviewer(user, request) &&
    request.status === "pending_review" &&
    Boolean(request.git_context?.pull_request_url);

  async function generate(force = false) {
    setUnchanged(null);
    try {
      setIsGenerating(true);
      const result = await generateAiReview(requestId, scope, force);
      setResults((prev) => [result, ...prev]);
      setIndex(0);
    } catch (err) {
      const detail = err?.response?.data?.detail;
      if (err?.response?.status === 409 && detail?.code === AI_REVIEW_UNCHANGED) {
        setUnchanged(detail.message);
      } else {
        onError(extractApiError(err, "Failed to generate the AI review."));
      }
    } finally {
      setIsGenerating(false);
    }
  }

  const total = results.length;

  return (
    <div className="details-section">
      <h3 className="details-section-title">AI Review</h3>

      {!isLoading && total > 1 && (
        <div className="ai-review-nav" aria-label="AI review history">
          <button
            type="button"
            className="btn btn-secondary btn-sm"
            onClick={() => setIndex((i) => Math.min(i + 1, total - 1))}
            disabled={index >= total - 1}
          >
            ◀ Older
          </button>
          <span className="ai-review-nav-label">
            Review {total - index} of {total}
            {index === 0 ? " (latest)" : ""}
          </span>
          <button
            type="button"
            className="btn btn-secondary btn-sm"
            onClick={() => setIndex((i) => Math.max(i - 1, 0))}
            disabled={index === 0}
          >
            Newer ▶
          </button>
        </div>
      )}

      {isLoading ? (
        <div className="empty-state" style={{ padding: "12px 0" }}>Loading AI review…</div>
      ) : shown ? (
        <AiReviewResult result={shown} requestRiskLevel={request.risk_level} />
      ) : (
        !canGenerate && (
          <div className="empty-state" style={{ padding: "12px 0" }}>No AI review yet.</div>
        )
      )}

      {!isLoading && canGenerate && (
        <div className={latest ? "ai-review-generate-below" : undefined}>
          <div className="form-group" style={{ marginBottom: "12px" }}>
            <label htmlFor="aiReviewScope">Scope</label>
            <select
              id="aiReviewScope"
              value={scope}
              onChange={(e) => setScope(e.target.value)}
              disabled={isGenerating}
            >
              {Object.entries(SCOPES).map(([value, option]) => (
                <option key={value} value={value}>
                  {option.label}
                </option>
              ))}
            </select>
            <span className="form-hint">{SCOPES[scope].help}</span>
          </div>
          <div className="page-actions" style={{ alignItems: "center" }}>
            <button className="btn btn-primary" type="button" onClick={() => generate(false)} disabled={isGenerating}>
              {isGenerating ? "Analysing…" : latest ? "Regenerate" : "Generate AI review"}
            </button>
            {isGenerating && <span className="form-hint" style={{ marginTop: 0 }}>This can take up to a minute.</span>}
          </div>
          <span className="form-hint">
            Covers up to 100 changed files; files over 200 KB are skipped; secret values are masked before sending.
          </span>
        </div>
      )}

      {unchanged && (
        <UnchangedDialog message={unchanged} onCancel={() => setUnchanged(null)} onConfirm={() => generate(true)} />
      )}
    </div>
  );
}
